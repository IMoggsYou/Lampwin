// Reads the next number, skipping spaces and commas; false at the end of the data.
bool Number(const char*& p, float* out) {
    while (*p == ' ' || *p == ',') ++p;
    char* end = nullptr;
    const float v = strtof(p, &end);
    if (end == p) return false;
    *out = v;
    p = end;
    return true;
}

bool Point(const char*& p, D2D1_POINT_2F* out) {
    return Number(p, &out->x) && Number(p, &out->y);
}

// One glyph's geometry; nullptr if the data (ours, fixed) could not be read.
ComPtr<ID2D1PathGeometry> Parse(ID2D1Factory* f, const char* data) {
    ComPtr<ID2D1PathGeometry> geometry;
    ComPtr<ID2D1GeometrySink> sink;
    if (FAILED(f->CreatePathGeometry(geometry.put())) || FAILED(geometry->Open(sink.put()))) return nullptr;
    sink->SetFillMode(D2D1_FILL_MODE_ALTERNATE);
    bool open = false;
    for (const char* p = data; *p;) {
        const char command = *p;
        if (command == ' ') {
            ++p;
            continue;
        }
        ++p;
        D2D1_POINT_2F a, b, c;
        if (command == 'M' && Point(p, &a)) {
            if (open) sink->EndFigure(D2D1_FIGURE_END_CLOSED);
            sink->BeginFigure(a, D2D1_FIGURE_BEGIN_FILLED);
            open = true;
        } else if (command == 'L' && open) {
            // "L x,y x,y ...": a polyline.
            while (Point(p, &a)) sink->AddLine(a);
        } else if (command == 'C' && open) {
            while (Point(p, &a) && Point(p, &b) && Point(p, &c)) sink->AddBezier({a, b, c});
        } else if (command == 'Z' && open) {
            sink->EndFigure(D2D1_FIGURE_END_CLOSED);
            open = false;
        } else {
            sink->Close();
            return nullptr;
        }
    }
    if (open) sink->EndFigure(D2D1_FIGURE_END_CLOSED);
    if (FAILED(sink->Close())) return nullptr;
    return geometry;
}

